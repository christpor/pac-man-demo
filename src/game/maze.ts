export function createMaze(): number[][] {
  return MAZE_TEMPLATE.map(row => [...row])
}

export function isWall(maze: number[][], x: number, y: number): boolean {
  if (y < 0 || y >= ROWS || x < 0 || x >= COLS) return true
  return maze[y][x] === CELL.WALL
}
